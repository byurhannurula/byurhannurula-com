const book = (
  slug: string,
  rest: Omit<ShelfItem, 'slug' | 'kind' | 'title' | 'by' | 'cover'>,
): ShelfItem => {
  const source = BOOKS.find((item) => item.slug === slug);
  if (!source) throw new Error(`No book "${slug}" in books.ts`);
  return {
    slug,
    kind: 'book',
    title: source.title,
    by: source.author,
    cover: source.cover,
    ...rest,
  };
};

